/** Corners of the square slice of side s, drawn in perspective: front edge at x = s, depth up and to the right. */
const square = (s: number): Vec[] => [[s, -s / 2], [s, s / 2], [1.3 * s, 0.7 * s], [1.3 * s, -0.3 * s]];

/** The pyramid of Worked Example 1 lying on its side, vertex at the origin, with the slice x m down from the vertex. */
function pyramid(caption: string, at?: number): PlotFigure {
  const [A, B, C, D] = square(3);
  const edge = (to: Vec, dashed = false): PlotItem => ({ type: 'segment', from: [0, 0], to, tone: 'ink', width: 1.5, dashed });
  const slice = (x: number): PlotItem[] => [
    { type: 'polygon', points: square(x), tone: 2, outline: true },
    { type: 'segment', from: [x, -x / 2], to: [x, x / 2], tone: 2, width: 2.5, label: 'x', anchor: 'w' },
    { type: 'segment', from: [0, -1.8], to: [x, -1.8], tone: 'ink', width: 1.5, label: 'x', anchor: 's' },
  ];
  return {
    kind: 'plot',
    caption,
    axes: false,
    equal: true,
    x: [-0.9, 4.3],
    y: [-2.4, 2.4],
    items: [
      { type: 'polygon', points: [[0, 0], A, B, C], tone: 1 },
      edge(A), edge(B), edge(C), edge(D, true),
      { type: 'segment', from: A, to: B, tone: 'ink', width: 1.5, label: '3', anchor: 'e' },
      { type: 'segment', from: B, to: C, tone: 'ink', width: 1.5 },
      { type: 'segment', from: C, to: D, tone: 'ink', width: 1.5, dashed: true },
      { type: 'segment', from: D, to: A, tone: 'ink', width: 1.5, dashed: true },
      { type: 'point', at: [0, 0], tone: 'ink', label: '\\text{vertex}', anchor: 'n' },
      ...(at === undefined ? [] : slice(at)),
    ],
    ...(at === undefined
      ? {
          animate: {
            param: 'x',
            range: [0.25, 3] as Vec,
            initial: 1.8,
            duration: 7,
            frame: slice,
            readout: (x: number) => `$x = ${fmt(x)}$ m below the vertex: the slice is a square of side $${fmt(x)}$ m, so $A(x) = x^2 = ${fmt(x * x)}\\text{ m}^2$.`,
          },
        }
      : {}),
  };
}

